import numpy as np, json, sys
cl=np.load('cl.npy'); N=len(cl); s=np.load('idx30.npy')
SC=700/1276; OY=30
seg=np.hypot(*np.diff(np.r_[cl,cl[:1]],axis=0).T)*SC; cum=np.r_[0,np.cumsum(seg)]; L=cum[-1]
pts=[]
for t in np.arange(0,85.01,0.1):
    i=s[min(int(round(t*30)),len(s)-1)]
    f=i%N; i0=int(f); a=f-i0; p=cl[i0]*(1-a)+cl[(i0+1)%N]*a
    prog=min(np.interp(min(i,N),np.arange(N+1),cum)/L,1.0)
    pts.append([round(t,2),round(p[0]*SC,1),round((p[1]-OY)*SC,1),round(prog,4)])
d="M"+" L".join(f"{x*SC:.1f},{(y-OY)*SC:.1f}" for x,y in cl[::2])+" Z"
open(sys.argv[1],'w').write("// Generated by scripts/ (yaw-rate DTW vs map curvature). t, x, y (card px), lap progress 0-1\nwindow.LAP_PATH="+json.dumps({"d":d,"len":round(L,1),"pts":pts})+";\n")
print(len(pts),L)
